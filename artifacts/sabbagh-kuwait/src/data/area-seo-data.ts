// قائمة معرفات المناطق الساحلية المعرضة للرطوبة والأملاح
const COASTAL_AREA_IDS = new Set([
  'al-salmiya', 'al-shaab', 'al-bidaa', 'salwa', 'al-fintas', 'mahboula',
  'abu-halifa', 'al-mangaf', 'al-fahaheel', 'sabah-al-ahmad-sea-city',
  'al-zour', 'al-khiran', 'bnaider', 'bneid-al-gar', 'dasman',
  'shuwaikh-residential', 'al-messilah', 'abu-al-hasaniya', 'al-doha', 'kazma'
]);

// قائمة معرفات مدن التوسع العمراني والقسائم الجديدة
const NEW_CITY_AREA_IDS = new Set([
  'al-mutlaa', 'sabah-al-ahmad-residential', 'west-abdullah-al-mubarak',
  'south-abdullah-al-mubarak', 'jaber-al-ahmad', 'south-saad-al-abdullah',
  'al-qairawan', 'al-masayel', 'abu-ftaira', 'al-fnaitees'
]);

/**
 * تحديد نمط المنطقة البيئي والعمراني
 */
export function getAreaTheme(area: Area): 'coastal' | 'new-city' | 'residential' | 'investment' | 'chalet' | 'commercial' {
  if (area.type === 'chalet' || area.id.includes('khiran') || area.id.includes('bnaider')) {
    return 'chalet';
  }
  if (NEW_CITY_AREA_IDS.has(area.id) || area.type === 'new-city') {
    return 'new-city';
  }
  if (COASTAL_AREA_IDS.has(area.id)) {
    return 'coastal';
  }
  if (area.type === 'investment') {
    return 'investment';
  }
  if (area.type === 'commercial') {
    return 'commercial';
  }
  return 'residential';
}

