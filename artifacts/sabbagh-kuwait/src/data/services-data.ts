/**
 * الحصول على تفاصيل الخدمة بواسطة الـ slug
 */
export function getServiceBySlug(slug: string): KuwaitService | undefined {
  return KUWAIT_SERVICES_DATA.find((s) => s.slug === slug || s.id === slug);
}

/**
 * الحصول على تفاصيل الخدمة بواسطة المعرف id
 */
export function getServiceById(id: string): KuwaitService | undefined {
  return KUWAIT_SERVICES_DATA.find((s) => s.id === id || s.slug === id);
}

/**
 * تصفية الخدمات حسب الفئة
 */
export function getServicesByCategory(category: string): KuwaitService[] {
  if (!category || category === 'all' || category === 'الكل') {
    return KUWAIT_SERVICES_DATA;
  }
  return KUWAIT_SERVICES_DATA.filter((s) => s.category === category);
}
